S="/tmp/claude-0/-home-user-stocks/898ea701-1503-5cc7-b811-4df21447c708/scratchpad"
t=open(S+"/rm/src/videos/orange/timing.ts").read()
TOTAL=int(re.search(r"TOTAL = (\d+)",t).group(1)); L=json.loads(re.search(r"export const L = (\[.*?\]);",t).group(1)); W=json.loads(re.search(r"export const W = (\{.*?\}) as const",t).group(1))
s=lambda f: round(f/30,3); lib=lambda k: sorted(glob.glob(S+f"/snd/lib/{k}__*.wav"))
c=lambda w: max(0,w-2)
cut={"hook":0,"m1":W["travelled"],"m2":W["whole"],"m3":W["world"],"india":c(W["newname"])-10,"persia":c(L[2]),"arab":c(L[3]),"quay":W["then3"],"europe":c(L[4]),"sea":c(L[5]),"china":c(W["found"]),"sintra":c(L[6]),"dutch":c(L[7]),"port":c(L[8]),"end":c(L[11]),"END":TOTAL}
order=list(cut); span=lambda k: (cut[k], cut[order[order.index(k)+1]])
acc=[]; A=lambda f,label,file,role,g,anchor="start",md=None,**kw: acc.append({"t":s(f),"label":label,"file":file,"role":role,"gain_db":g,"anchor":anchor,**({"max_dur":md} if md else {}),**kw})
wh=lib("whoosh"); gl=lib("medal_glint"); pop=lib("pop")[0]; clink=lib("clink")[0]
for k in ["m1","m2","m3"]: A(cut[k]-3,f"montage whoosh {k}",wh[0],"whoosh",-6,md=0.5,lowpass=6000)
A(W["then3"]-5,"whip to the quay",wh[1 % len(wh)],"whoosh",-2,md=0.6)
A(W["naranga"],"sparkle naranga",gl[0],"chime",-6,"arrive",md=1.0)
A(W["narang2"]-14,"paint brush swish",wh[2 % len(wh)],"whoosh",-10,md=0.5,lowpass=4000)
A(W["color"],"swatch blooms",gl[1 % len(gl)],"chime",-8,"arrive",md=0.9)
A(W["naranj"]-6,"sign flips",wh[0],"whoosh",-4,md=0.45)
A(W["naranj"]+2,"sparkle naranj",gl[0],"chime",-8,"arrive",md=0.8)
A(W["laranja"],"sparkle laranja",gl[2 % len(gl)],"chime",-8,"arrive",md=0.8)
A(W["theN"],"the N pops loose",pop,"hit",-4,"arrive",md=0.6)
A(W["fell"]+4,"the N lands: clink",clink,"hit",0,"arrive",md=1.0)
A(W["sweeter"],"sweet sparkle",gl[1 % len(gl)],"chime",-6,"arrive",md=1.0)
A(W["eat"],"bite",pop,"hit",-10,"arrive",md=0.4,pitch=-5)
A(W["say"]-4,"whisper: hush",wh[3 % len(wh)],"whoosh",-12,md=0.8,lowpass=3000)
A(W["santra"],"SANTRA pop",pop,"hit",3,"arrive",md=0.8)
A(W["santra"]+1,"SANTRA sparkle",gl[0],"chime",-2,"arrive",md=1.3)
beds=[]; B=lambda k,label,file,g,fi=0.1,fo=0.2: beds.append({"t":s(span(k)[0]),"label":label,"file":file,"role":"ambience","gain_db":g,"anchor":"start","loop_to":s(span(k)[1]-span(k)[0]),"max_dur":s(span(k)[1]-span(k)[0]),"fade_in":fi,"fade_out":fo})
wind=lib("bed_wind"); crowd=lib("bed_crowd"); sea=lib("bed_sea")
B("hook","orchard breeze",wind[0],-2); B("india","orchard breeze",wind[0],-2); B("m1","caravan wind",wind[1],0); B("persia","caravan wind",wind[1],0)
B("arab","souk murmur",crowd[0],-4); B("m2","harbour",sea[0],0); B("quay","harbour",sea[0],0); B("m3","square murmur",crowd[0],-5); B("europe","square murmur",crowd[0],-5)
B("sea","open sea",sea[1],2); B("china","port murmur",crowd[0],-6); B("china","port sea",sea[0],-2)
B("sintra","hill breeze",wind[1],-4); B("dutch","market murmur",crowd[0],-5); B("port","Indian port sea",sea[0],-1); B("port","port murmur",crowd[0],-8); B("end","evening sea",sea[1],-3,0.1,1.0)
beds.append({"t":s(W["crazy"]-6),"label":"Europe goes crazy: crowd","file":crowd[1],"role":"ambience","gain_db":6,"anchor":"start","max_dur":s(cut["dutch"]-W["crazy"]+6),"fade_in":0.1,"fade_out":0.3})
dur=round(TOTAL/30,3)
for n,cu in [("acc",acc),("beds",beds)]: json.dump({"duration":dur,"keep_audio":"no","cues":cu},open(f"{n}.json","w"),indent=1)
