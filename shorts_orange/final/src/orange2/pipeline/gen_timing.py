# words.json -> rm/src/videos/orange2/timing.ts: every word as W["<line>.<word>"] (first occurrence) + Wn array; line starts L; TOTAL.
import json, re
S='/tmp/claude-0/-home-user-stocks/898ea701-1503-5cc7-b811-4df21447c708/scratchpad'
D=json.load(open(S+'/orange2/build/words.json')); F=lambda t: round(t*30)
norm=lambda w: re.sub(r"[^a-z0-9]","",w.lower())
K={}; E={}
for x in D['words']:
    k=f"{x['line']}.{norm(x['w'])}"
    if k not in K: K[k]=F(x['t']); E[k]=F(x['t']+x['d'])
L=[F(l['t0']) for l in D['lines']]; T=F(D['total'])
open(S+'/rm/src/videos/orange2/timing.ts','w').write(
 "// generated by orange2/build/gen_timing.py from words.json (whisper word starts on voice.wav, 1.2x). Frames at 30 fps.\n"
 f"export const TOTAL = {T};\nexport const L = {json.dumps(L)};\nexport const W: Record<string, number> = {json.dumps(K)};\nexport const WE: Record<string, number> = {json.dumps(E)};\n")
print(T,L)
